// Called by prepare-first-of-year.py. Sample the same rigs used by the server.
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {Vector3} from 'three';
import {loadRig, createRig} from '../server/rig.js';
import {createRetargetedRig, boneKey} from '../server/retarget.js';
import {characters} from '../server/characters.js';
import {analyzeFootfalls, rootAt} from '../public/scenes/disco-contacts.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const config=JSON.parse(await readFile(path.join(root,'config.json')));
const entry=config.animations.find(e=>e.id==='first-of-year');
const source=await loadRig(path.resolve(root,entry.file));
const motion=JSON.parse(await readFile(process.argv[2],'utf8'));
const profiles={};
for(const character of [{id:'embedded'},...characters]){
  const rig=character.id==='embedded'?createRig(source,entry):createRetargetedRig(source,entry,await loadRig(path.resolve(root,character.file),false),character.scale);
  const bones=new Map();rig.root.traverse(n=>{if(n.isBone)bones.set(boneKey(n.name),n);});
  const feet=['Left','Right'].map(side=>[bones.get(side+'Foot'),bones.get(side+'ToeBase')].filter(Boolean));
  const vector=new Vector3(),samples=[];
  for(let i=0;i<motion.root_xz.length;i++){
    const time=i/motion.fps;rig.sample(time);
    samples.push({time,root:rootAt(motion,time),feet:feet.map(pair=>{
      const points=pair.map(b=>b.getWorldPosition(vector).toArray());
      return points.reduce((a,b)=>a[1]<b[1]?a:b);
    })});
  }
  const {floor,events}=analyzeFootfalls(samples,motion.fps);
  // Floor samples at 10 Hz are plenty for the smoothed lower envelope.
  profiles[character.id]={floorFps:10,floor:floor.filter((_,i)=>i%3===0),events};
  console.log(`${character.id}: ${events.length} footfalls; floor ${Math.min(...floor).toFixed(3)}–${Math.max(...floor).toFixed(3)} m`);
}
const output={...motion,profiles};
const destination=path.join(root,'public/scenes/data/first-of-year.js');
await mkdir(path.dirname(destination),{recursive:true});
await writeFile(destination,'// Generated by scripts/prepare-first-of-year.py from the original capture and Motion Stage rigs.\nexport default '+JSON.stringify(output,(_,v)=>typeof v==='number'?Math.round(v*1e5)/1e5:v)+';\n');
console.log(destination);
